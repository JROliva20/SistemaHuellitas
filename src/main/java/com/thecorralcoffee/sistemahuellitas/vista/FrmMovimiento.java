    private void cargarProductos() {
    cbmProducto.removeAllItems();
    List<Producto> productos = productoController.listarProductos();
    for (Producto p : productos) {
        cbmProducto.addItem(p.getId() + " - " + p.getNombre());
    }
    }
    
    private void cargarTipos() {
    cbmTipo.removeAllItems();
    cbmTipo.addItem("ENTRADA");
    cbmTipo.addItem("SALIDA");
    }  
    private void cargarMovimientos() {
    List<Movimientos> movimientos = movimientoController.listarMovimientos();
    DefaultTableModel modelo = (DefaultTableModel) tblMovimientos.getModel();
    modelo.setRowCount(0);
    for (Movimientos m : movimientos) {
        Producto producto = productoController.buscarProducto(m.getProductoId());
        String nombreProducto = "";
        if (producto != null) {
            nombreProducto = producto.getNombre();
        }
        modelo.addRow(new Object[]{
            m.getId(),
            nombreProducto,
            m.getTipo(),
            m.getCantidad(),
            m.getFecha()
        });
    }
    }    
    private void limpiarCampos() {
    txtCantidad.setText("");
    if (cbmProducto.getItemCount() > 0) {
        cbmProducto.setSelectedIndex(0);
    }
    if (cbmTipo.getItemCount() > 0) {
        cbmTipo.setSelectedIndex(0);
    }
    txtCantidad.requestFocus();
    }


