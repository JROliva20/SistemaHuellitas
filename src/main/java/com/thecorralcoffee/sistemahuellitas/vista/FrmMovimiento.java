    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tblMovimientos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,"Selecciona un movimiento.");
        return;
    }
    int id = (int) tblMovimientos.getValueAt(fila, 0);
    Movimientos movimiento = movimientoController.buscarPorId(id);
    if (movimiento == null) {
        JOptionPane.showMessageDialog(this,"No se encontró el movimiento.");
        return;
    }
    movimientoEditandoId = movimiento.getId();

    //seleccionar producto
    for (int i = 0; i < cbmProducto.getItemCount(); i++) {
        String item = cbmProducto.getItemAt(i);
        int productoId = Integer.parseInt(item.split(" - ")[0]);
        if (productoId == movimiento.getProductoId()) {
            cbmProducto.setSelectedIndex(i);
            break;
        }
    }
    //seleccionar tipo
    cbmTipo.setSelectedItem(movimiento.getTipo());
    //cantidad
    txtCantidad.setText(String.valueOf(movimiento.getCantidad()));
    //cambiar botón
    btnRegistroMovi.setText("Actualizar Movimiento");
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblMovimientos.getSelectedRow();
    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Selecciona un movimiento.");
        return;
    }
    
    int id = (int) tblMovimientos.getValueAt(fila, 0);

    int confirmar = JOptionPane.showConfirmDialog(
            this,"¿Deseas eliminar este movimiento?","Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmar == JOptionPane.YES_OPTION) {
        if (movimientoController.eliminarMovimiento(id)) {
            JOptionPane.showMessageDialog(this,"Movimiento eliminado correctamente.");

            cargarMovimientos();

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar el movimiento.");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnRegistroMoviActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistroMoviActionPerformed
        if (cbmProducto.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this, "Selecciona un producto.");
        return;
    }

    if (txtCantidad.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingresa una cantidad.");
        txtCantidad.requestFocus();
        return;
    }

    int cantidad;

    try {
        cantidad = Integer.parseInt(txtCantidad.getText().trim());

        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor que 0.");
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La cantidad debe ser un número entero.");
        txtCantidad.requestFocus();
        return;
    }

    //obtener ID del producto
    String productoSeleccionado = cbmProducto.getSelectedItem().toString();
    int productoId = Integer.parseInt(productoSeleccionado.split(" - ")[0]);

    String tipo = cbmTipo.getSelectedItem().toString();

    if (movimientoEditandoId == -1) {

        Movimientos movimiento = new Movimientos();
        movimiento.setTipo(tipo);
        movimiento.setCantidad(cantidad);
        movimiento.setProductoId(productoId);

        if (movimientoController.insertarMovimiento(movimiento)) {

            JOptionPane.showMessageDialog(this,
                    "Movimiento registrado correctamente.");
            cargarMovimientos();
            limpiarCampos();

        } else {
            JOptionPane.showMessageDialog(this,"No se pudo registrar el movimiento.");
        }

    } else {

        Movimientos movimiento = movimientoController.buscarPorId(movimientoEditandoId);

        if (movimiento != null) {

            movimiento.setTipo(tipo);
            movimiento.setCantidad(cantidad);
            movimiento.setProductoId(productoId);

            if (movimientoController.actualizarMovimiento(movimiento)) {

                JOptionPane.showMessageDialog(this,"Movimiento actualizado correctamente.");
                cargarMovimientos();
                limpiarCampos();
                movimientoEditandoId = -1;
                btnRegistroMovi.setText("Registrar Movimiento");

            } else {

                JOptionPane.showMessageDialog(this,"No se pudo actualizar el movimiento.");
            }
        }
    }
    }//GEN-LAST:event_btnRegistroMoviActionPerformed

