    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (usuarioEditandoId == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.");
        return;
        }
        String nombre = txtNombre.getText().trim();
        String usuario = txtUsuario.getText().trim();
        String clave = txtClave.getText().trim();
        String rol = cbmRol.getSelectedItem().toString();
        if (nombre.isEmpty() || usuario.isEmpty() || clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }
        Usuario u = new Usuario(
        usuarioEditandoId,
            nombre,
            usuario,
            clave,
            rol
        );
        if (usuarioController.actualizarUsuario(u)) {
            JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente.");
            cargarUsuarios();
            limpiarCampos();
        } else {
        JOptionPane.showMessageDialog(this, "No se pudo actualizar el usuario.");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (usuarioEditandoId == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.");
        return;
        }

        int respuesta = JOptionPane.showConfirmDialog(
            this,"¿Está seguro de eliminar este usuario?",
                "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
        );

        if (respuesta == JOptionPane.YES_OPTION) {
            if (usuarioController.eliminarUsuario(usuarioEditandoId)) {
            JOptionPane.showMessageDialog(this, "Usuario eliminado correctamente.");
            cargarUsuarios();
            limpiarCampos();
        } else {
        JOptionPane.showMessageDialog(this, "No se pudo eliminar el usuario.");
    }
}
    }//GEN-LAST:event_btnEliminarActionPerformed

