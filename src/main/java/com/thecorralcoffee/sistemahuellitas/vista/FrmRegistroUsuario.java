    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String nombre = txtNombre.getText().trim();
        String usuario = txtUsuario.getText().trim();
        String clave = txtClave.getText().trim();

    if (nombre.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese el nombre del usuario.");
        txtNombre.requestFocus();
        return;
    }

    if (nombre.length() < 3) {
        JOptionPane.showMessageDialog(this, "El nombre debe tener al menos 3 caracteres.");
        txtNombre.requestFocus();
        return;
    }

    if (!nombre.matches("[a-zA-ZáéíóúÁÉÍÓÚñÑ ]+")) {
        JOptionPane.showMessageDialog(this, "El nombre solo puede contener letras y espacios.");
        txtNombre.requestFocus();
        return;
    }

    if (usuario.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese el nombre de usuario.");
        txtUsuario.requestFocus();
        return;
    }

    if (usuario.length() < 4) {
        JOptionPane.showMessageDialog(this, "El usuario debe tener al menos 4 caracteres.");
        txtUsuario.requestFocus();
        return;
    }

    if (!usuario.matches("[a-zA-Z0-9._-]+")) {
        JOptionPane.showMessageDialog(this, "El usuario solo puede contener letras, números, punto, guion y guion bajo.");
        txtUsuario.requestFocus();
        return;
    }

    if (clave.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese la contraseña.");
        txtClave.requestFocus();
        return;
    }

    if (clave.length() < 6) {
        JOptionPane.showMessageDialog(this, "La contraseña debe tener al menos 6 caracteres.");
        txtClave.requestFocus();
        return;
    }

    if (cbmRol.getSelectedItem() == null || cbmRol.getSelectedItem().toString().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Seleccione un rol.");
        cbmRol.requestFocus();
        return;
    }

    String rol = cbmRol.getSelectedItem().toString();

    Usuario usuarioNuevo = new Usuario(
        nombre,
        usuario,
        clave,
        rol
    );

    if (usuarioController.insertarUsuario(usuarioNuevo)) {
        JOptionPane.showMessageDialog(this, "Usuario registrado correctamente.");
        cargarUsuarios();
        limpiarCampos();
    } else {
        JOptionPane.showMessageDialog(this, "No se pudo registrar el usuario. Verifique que el nombre de usuario no esté repetido.");
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        int fila = tblUsuarios.getSelectedRow();

    if (fila >= 0) {
        usuarioEditandoId = Integer.parseInt(
            tblUsuarios.getValueAt(fila, 0).toString()
        );

        Usuario usuario = usuarioController.buscarUsuario(usuarioEditandoId);

        if (usuario != null) {
            txtNombre.setText(usuario.getNombre());
            txtUsuario.setText(usuario.getUsuario());
            txtClave.setText(usuario.getClaveHash());
            cbmRol.setSelectedItem(usuario.getRol());
        }
    }
    }//GEN-LAST:event_tblUsuariosMouseClicked

